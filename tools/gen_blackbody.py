"""Generate fluxmax/color/blackbody_table.py from redshift's colorramp.c.

Provenance: redshift (GPL-3.0) src/colorramp.c `blackbody_color`, 3 floats per
100 K from 1000 K. Run once: `python tools/gen_blackbody.py` (needs network).
"""
import pathlib
import re
import urllib.request

URL = "https://raw.githubusercontent.com/jonls/redshift/master/src/colorramp.c"


def main() -> None:
    src = urllib.request.urlopen(URL).read().decode()
    body = re.search(r"blackbody_color\[\]\s*=\s*\{(.+?)\};", src, re.S).group(1)
    floats = [float(x) for x in re.findall(r"[-+]?\d*\.\d+", body)]
    triples = list(zip(floats[0::3], floats[1::3], floats[2::3], strict=True))
    lines = [
        "# AUTO-GENERATED by tools/gen_blackbody.py -- do not edit.",
        "# Source: redshift src/colorramp.c blackbody_color (GPL-3.0).",
        "WHITEPOINTS = {",
    ]
    for i, (r, g, b) in enumerate(triples):
        lines.append(f"    {1000 + i * 100}: ({r!r}, {g!r}, {b!r}),")
    lines.append("}")
    out = pathlib.Path("fluxmax/color/blackbody_table.py")
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out} with {len(triples)} rows")


if __name__ == "__main__":
    main()
